/// The per-instance expansion of a batch over a table (cuda::DeviceExpander, PerInstance): each instance's rows are
/// gathered into a part (rows[j]: the batch row at part position j) and expanded apart; these put the parts' results
/// back in batch order. launch_part_counts: counts[rows[j]] = offsets[j + 1] - offsets[j] for the part's n positions.
cudaError_t launch_part_counts(const u32* rows, const i32* offsets, u64 n, u32* counts, cudaStream_t s);
/// One part's successors [0, total) (part-local parents and CSR offsets; rows of `words` words, labels of
/// `label_width` columns) to their batch positions: successor j of part position p = parent[j] goes to row
/// batch_offsets[r] + j - offsets[p] of the outputs, r = rows[p] (with `outer`, r = outer[rows[p]]: the part of a part
/// of the batch, cuda::DeviceExpander's per-instance parts of a suite's domain), widened to out_words (zero words) and
/// out_label_width (-1 entries); not written at or past capacity; null outputs are skipped; its parent label becomes r.
/// A group of lanes per successor (the wider of its output row and labels, a power of two, at most a warp) copies its
/// words and labels coalesced.
struct PartScatter
{
    const u32* rows = nullptr;
    const u32* outer = nullptr;
    const i32* offsets = nullptr;
    const i32* batch_offsets = nullptr;
    u64 total = 0;
    const i32* parent = nullptr;
    const u64* succ = nullptr;
    u32 words = 0, out_words = 0;
    const i32* schema = nullptr;
    const i32* binding = nullptr;
    u32 label_width = 0, out_label_width = 0;
    const u8* goal = nullptr;
    u64 capacity = 0;
    u64* out_succ = nullptr;
    i32* out_schema = nullptr;
    i32* out_binding = nullptr;
    i32* out_parent = nullptr;
    u8* out_goal = nullptr;
};
cudaError_t launch_part_scatter(const PartScatter& p, cudaStream_t s);

/// The launch-order keys of a batch's instances: instance k's key key[k] (device [instances]), in [0, count).
struct OrderKeys
{
    const u32* key = nullptr;
    u32 count = 1;
};
/// The launch order of a multi-instance batch: order[j * stride] = the row at position j, pos[row * stride] = its
/// position, sorted by the key of the row's instance (keys.key[inst[row]]: in a table the rank of the instance's launch
/// group and the instance; in a suite its domain's instances come first), stable by row within a key. Task ids outside
/// [0, instances) take key 0, a key at or past keys.count sorts as keys.count - 1. A counting sort over the keys.count
/// keys when they are at most 1024 (and the batch's (key, tile) counts fit the scratch), else CUB's radix sort over
/// their bits; the same order either way. Scratch: order_temp_bytes(n) bytes.
[[nodiscard]] u64 order_temp_bytes(u64 n);
cudaError_t launch_order(const u32* inst, u32 instances, OrderKeys keys, u64 n, void* temp, u64 temp_bytes, u32* order,
                         u32* pos, u64 stride, cudaStream_t s);
/// Sets *bad when the order is not a permutation of [0, n) (pos[order[j]] != j for some j): a batch rearranged or
/// resized since the order was computed.
cudaError_t launch_check_order(const u32* order, const u32* pos, u64 stride, u64 n, u32* bad, cudaStream_t s);
/// Sets *bad unless order / pos are launch_order's order of the batch: a permutation of [0, n) with its inverse, sorted
/// by key and within a key by row (the debug builds' check of every launch order, cuda/src/table_launch.hpp).
cudaError_t launch_check_order_keys(const u32* inst, u32 instances, OrderKeys keys, u64 n, const u32* order,
                                    const u32* pos, u64 stride, u32* bad, cudaStream_t s);
