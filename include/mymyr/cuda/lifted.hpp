/// Where launch_put_multi puts its rows besides `out`. Unmapped (rows null): row j at row j of out.words, and its
/// goal flag at goal[j]. Mapped (the labeled rows are a part of a larger batch, in scratch): successor k of the
/// part's state at position q (q = its parent label; k = j - offsets[(q - labels.parent_base) * S]) goes to row
/// r = batch_offsets[rows[q]] + k of the batch's outputs, written below `capacity` (the rows past it still count their
/// widths and missing atoms): its successor words (out.words is the batch's), its labels widened to label_width (-1
/// past labels.label_width), schema, parent rows[q] and goal flag. Null outputs are skipped.
struct PutRows
{
    const u32* rows = nullptr;           // [part positions] the batch row of each (null: unmapped)
    const i32* batch_offsets = nullptr;  // [batch rows + 1] the batch's CSR offsets
    u64 capacity = 0;
    u32* binding = nullptr;
    u32 label_width = 0;
    u32* schema = nullptr;
    u32* parent = nullptr;
    u8* goal = nullptr;  // the goal flag of each written row (goals without derived literals; needs out.words)
};
