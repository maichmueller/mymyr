cudaError_t launch_place_host(HostRows h, const u32* offsets, u32 num_schemas, Labels labels, u64* out_words, u32 out_width,
                              cudaStream_t s);

/// Scatters host counts: counts[segment[i]] = value[i].
cudaError_t launch_scatter_counts(const u32* segment, const u32* value, u64 n, u32* counts, cudaStream_t s);

/// Exclusive prefix sum of n u32 values (CUB): temp_bytes() is the scratch launch_scan needs for n values.
[[nodiscard]] u64 scan_temp_bytes(u64 n);
cudaError_t launch_scan(const u32* in, u32* out, u64 n, void* temp, u64 temp_bytes, cudaStream_t s);

/// rl::expand's CSR offsets from the segment offsets: offsets_out[i] = base + seg_offsets[i * S] for i <= rows (the
/// entry at rows * S is the total), as int32.
cudaError_t launch_state_offsets(const u32* seg_offsets, u32 num_schemas, u64 rows, u64 base, i32* offsets_out,
                                 cudaStream_t s);

